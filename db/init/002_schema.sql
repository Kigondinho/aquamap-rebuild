-- AquaMap database initialisation, step 2: tables.
--
-- Spatial data is stored in EPSG:32737 (WGS 84 / UTM zone 37S), a metric CRS, so lengths and
-- distances are in metres directly. Nairobi (about 1.3 deg S) lies in the southern hemisphere.
-- The API reprojects to EPSG:4326 (ST_Transform) when it serves GeoJSON.
--
-- Raw road and river geometry is kept apart from analysis results: re-scoring never rewrites the
-- geometry tables, and the results table records which configuration and run produced each score.

-- ---------------------------------------------------------------------------
-- Users and authentication
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    user_id       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,           -- salted adaptive hash; never the password
    full_name     VARCHAR(120) NOT NULL DEFAULT '',
    role          VARCHAR(16)  NOT NULL DEFAULT 'user',
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT users_email_key       UNIQUE (email),
    CONSTRAINT users_role_valid      CHECK (role IN ('admin', 'user')),
    CONSTRAINT users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT users_email_not_blank CHECK (length(btrim(email)) > 3)
);

-- One-time codes for the optional email second factor.
CREATE TABLE IF NOT EXISTS auth_otps (
    otp_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    UUID         NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    otp_hash   VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    attempts   SMALLINT     NOT NULL DEFAULT 0,
    consumed   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT auth_otps_attempts_nonneg CHECK (attempts >= 0)
);

-- ---------------------------------------------------------------------------
-- Data provenance and scoring configuration
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS spatial_layers (
    layer_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layer_name    VARCHAR(100) NOT NULL,
    layer_type    VARCHAR(16)  NOT NULL,
    source        VARCHAR(100),
    source_url    TEXT,
    license       VARCHAR(100),
    feature_count INTEGER,
    uploaded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT spatial_layers_type_valid  CHECK (layer_type IN ('roads', 'rivers', 'dem')),
    CONSTRAINT spatial_layers_count_valid CHECK (feature_count IS NULL OR feature_count >= 0)
);

CREATE TABLE IF NOT EXISTS scoring_config (
    config_version  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weights         JSONB   NOT NULL,   -- {elevation, river, slope, surface}; sum to 1
    breakpoints     JSONB   NOT NULL,   -- per numeric factor: edges and score ladder
    surface_map     JSONB   NOT NULL,   -- OSM surface value -> 0..1
    tier_thresholds JSONB   NOT NULL,   -- ascending cut-offs for Medium / High / Severe
    is_active       BOOLEAN NOT NULL DEFAULT FALSE,
    created_by      UUID REFERENCES users (user_id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pipeline_runs (
    run_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_version   INTEGER REFERENCES scoring_config (config_version),
    started_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at      TIMESTAMPTZ,
    status           VARCHAR(12) NOT NULL DEFAULT 'running',
    segments_scored  INTEGER,
    segments_flagged INTEGER,
    input_summary    JSONB,
    error            TEXT,
    CONSTRAINT pipeline_runs_status_valid CHECK (status IN ('running', 'succeeded', 'failed')),
    CONSTRAINT pipeline_runs_dates_valid  CHECK (finished_at IS NULL OR finished_at >= started_at)
);

-- ---------------------------------------------------------------------------
-- Road segments (geometry and OSM attributes only)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS road_segments (
    road_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layer_id     INTEGER REFERENCES spatial_layers (layer_id),
    osm_id       BIGINT,                         -- one OSM way may be split into several segments
    name         VARCHAR(255),
    highway_type VARCHAR(50) NOT NULL,
    surface      VARCHAR(50),
    geom         geometry(LineString, 32737) NOT NULL,
    length_m     DOUBLE PRECISION GENERATED ALWAYS AS (ST_Length(geom)) STORED,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT road_geom_valid CHECK (ST_IsValid(geom) AND NOT ST_IsEmpty(geom)),
    CONSTRAINT road_highway_not_blank CHECK (length(btrim(highway_type)) > 0)
);

-- Phase 6 ingestion key. (osm_element, osm_id, part_no) identifies one stored segment: part_no is the
-- position of the segment within its OSM feature (0 unless a MultiLineString was split). The unique
-- index in 003 makes re-running the loader an upsert instead of a duplicate insert.
-- Added with ALTER so that databases created before Phase 6 are upgraded by `python -m app.db_tools init`.
ALTER TABLE road_segments ADD COLUMN IF NOT EXISTS osm_element VARCHAR(8) NOT NULL DEFAULT 'way';
ALTER TABLE road_segments ADD COLUMN IF NOT EXISTS part_no     INTEGER    NOT NULL DEFAULT 0;

-- ---------------------------------------------------------------------------
-- River centrelines (OSM waterways)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS river_centerlines (
    river_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layer_id   INTEGER REFERENCES spatial_layers (layer_id),
    osm_id     BIGINT,
    name       VARCHAR(255),
    waterway   VARCHAR(32),                      -- river | stream | canal | drain
    geom       geometry(LineString, 32737) NOT NULL,
    length_m   DOUBLE PRECISION GENERATED ALWAYS AS (ST_Length(geom)) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT river_geom_valid CHECK (ST_IsValid(geom) AND NOT ST_IsEmpty(geom))
);

-- Phase 6 ingestion key. (osm_element, osm_id, part_no) identifies one stored segment: part_no is the
-- position of the segment within its OSM feature (0 unless a MultiLineString was split). The unique
-- index in 003 makes re-running the loader an upsert instead of a duplicate insert.
-- Added with ALTER so that databases created before Phase 6 are upgraded by `python -m app.db_tools init`.
ALTER TABLE river_centerlines ADD COLUMN IF NOT EXISTS osm_element VARCHAR(8) NOT NULL DEFAULT 'way';
ALTER TABLE river_centerlines ADD COLUMN IF NOT EXISTS part_no     INTEGER    NOT NULL DEFAULT 0;

-- ---------------------------------------------------------------------------
-- Vulnerability analysis results (one current result per road)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS road_vulnerability (
    road_id             BIGINT PRIMARY KEY REFERENCES road_segments (road_id) ON DELETE CASCADE,
    run_id              INTEGER REFERENCES pipeline_runs (run_id) ON DELETE SET NULL,
    config_version      INTEGER NOT NULL REFERENCES scoring_config (config_version),
    -- measured inputs
    elevation_m         REAL,
    slope_pct           REAL,
    river_dist_m        REAL,
    -- normalised factor scores, 0..1 (higher = more vulnerable)
    score_elevation     REAL,
    score_river         REAL,
    score_slope         REAL,
    score_surface       REAL,
    -- result
    vulnerability_index NUMERIC(4, 3),
    risk_category       VARCHAR(8),
    -- zero or more of: no_dem, surface_missing, no_river
    data_flags          TEXT[] NOT NULL DEFAULT '{}',
    computed_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT vuln_inputs_nonneg CHECK (
        (slope_pct IS NULL OR slope_pct >= 0) AND (river_dist_m IS NULL OR river_dist_m >= 0)
    ),
    CONSTRAINT vuln_scores_in_range CHECK (
        (score_elevation IS NULL OR score_elevation BETWEEN 0 AND 1) AND
        (score_river     IS NULL OR score_river     BETWEEN 0 AND 1) AND
        (score_slope     IS NULL OR score_slope     BETWEEN 0 AND 1) AND
        (score_surface   IS NULL OR score_surface   BETWEEN 0 AND 1)
    ),
    CONSTRAINT vuln_ivi_in_range CHECK (
        vulnerability_index IS NULL OR vulnerability_index BETWEEN 0 AND 1
    ),
    CONSTRAINT vuln_tier_valid CHECK (
        risk_category IS NULL OR risk_category IN ('Low', 'Medium', 'High', 'Severe')
    ),
    -- a score and its tier exist together or not at all
    CONSTRAINT vuln_ivi_and_tier_together CHECK (
        (vulnerability_index IS NULL) = (risk_category IS NULL)
    )
);
